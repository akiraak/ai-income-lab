def live(path):
    """experiments/live-trading・tastytrade-api-sample。"""
    name = path.rsplit("/", 1)[-1]
    tasty = "tastytrade-api-sample" in path
    if re.search(r"paper|yardstick|closes", name): hikae = "スナップショット"      # 終値のスナップショット（closes.json）
    elif tasty: hikae = "バックアップ"
    else: hikae = "ジャーナル"                                                    # 発注の前に書く記録（journal.jsonl）
    return [
        (r"終値の控え", "終値のスナップショット"), (r"売買履歴の控え", "売買履歴のバックアップ"), (_HI, hikae),
        (r"「仮」の印", "「仮」のラベル"), (_IN, "フラグ"),
        (r"段 (?=[0-9])", "ステージ " if tasty else "ステップ "),
        (_KI, "ツリー"),
        (r"操作の口", "操作の手段"), (_KO, "オプション"),
    ]

