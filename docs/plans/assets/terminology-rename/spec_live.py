SNAP_LINES = {1336, 1391, 1496, 1497}          # 終値のスナップショット（closes.json）の話の行

def PRE(text):
    lines = text.split("\n")
    for n in SNAP_LINES:
        parts = re.split(r"(「[^」]*」|`[^`]*`)", lines[n - 1])
        for i, p in enumerate(parts):
            if p.startswith(("「", "`")): continue
            p = p.replace("朝だけ控えると", "朝だけスナップショットを取ると")
            parts[i] = re.sub(r"控え(?![たるて])", "スナップショット", p)
        lines[n - 1] = "".join(parts)
    return "\n".join(lines)

